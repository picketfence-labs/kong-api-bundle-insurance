def mynumber_check_digit(body11: str) -> int:
    """マイナンバー(個人番号)11桁の本体部分から検査用数字を算出する。

    総務省告示に定める算出方法: 右端(1桁目)から数えた位置 n(1〜11)に対する
    重み Pn は 1<=n<=6 で n+1、7<=n<=11 で n-5。sum(digit_n * Pn) を11で割った
    余り r について、r<=1 なら検査用数字は0、それ以外は 11-r。
    """
    digits = [int(c) for c in body11]
    total = 0
    for i, d in enumerate(digits):
        n = len(digits) - i  # 右端からの位置(1-indexed)
        weight = (n + 1) if 1 <= n <= 6 else (n - 5)
        total += d * weight
    remainder = total % 11
    return 0 if remainder <= 1 else 11 - remainder


def generate_my_number(rng: random.Random) -> str:
    body = "".join(str(rng.randint(0, 9)) for _ in range(11))
    return body + str(mynumber_check_digit(body))


def generate_postal_address(rng: random.Random):
    pref_code, prefecture, city, postal_code = rng.choice(PREFECTURE_CITY_POSTAL)
    chome = rng.choice(CHOME_BANCHI)
    building = rng.choice(BUILDING_NAMES)
    address_line = f"{chome}" + (f" {building}" if building else "")
    return pref_code, postal_code, prefecture, city, address_line


def generate_mobile_number(rng: random.Random) -> str:
    prefix = rng.choice(MOBILE_PREFIXES)
    return f"{prefix}-{rng.randint(0, 9999):04d}-{rng.randint(0, 9999):04d}"


def generate_landline_number(rng: random.Random, pref_code: str) -> str:
    area = AREA_CODE_BY_PREF_CODE.get(pref_code, "03")
    return f"{area}-{rng.randint(0, 9999):04d}-{rng.randint(0, 9999):04d}"


def generate_bank_account(rng: random.Random) -> dict:
    bank_name, branches = rng.choice(BANKS)
    return {
        "bank_name": bank_name,
        "branch_name": rng.choice(branches),
        "account_type": rng.choice(ACCOUNT_TYPES),
        "account_number": f"{rng.randint(0, 9999999):07d}",
    }


def generate_full_name(rng: random.Random, gender: str):
    last_kanji, last_kana = rng.choice(LAST_NAMES)
    pool = FIRST_NAMES_MALE if gender == "男性" else FIRST_NAMES_FEMALE if gender == "女性" else (
        FIRST_NAMES_MALE + FIRST_NAMES_FEMALE
    )
    first_kanji, first_kana = rng.choice(pool)
    return last_kanji, first_kanji, last_kana, first_kana


def format_id(prefix: str, seq: int, width: int = 6) -> str:
    return f"{prefix}-{seq:0{width}d}"
